const (
	wpURL       = "https://wordpress.org/latest.tar.gz"
	wpCLIVer    = "2.11.0"
	wpCLIURL    = "https://github.com/wp-cli/wp-cli/releases/download/v" + wpCLIVer + "/wp-cli-" + wpCLIVer + ".phar"
	wpCLIPath   = "/usr/local/bin/wp"
	maxTarBytes = 300 << 20
)

// phpPackages are the PHP extensions WordPress and its popular plugins need.
var phpPackages = []string{"php-fpm", "php-mysql", "php-curl", "php-gd", "php-mbstring", "php-xml", "php-zip", "php-intl", "php-cli"}

var (
	userRe  = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_.-]{2,30}$`)
	emailRe = regexp.MustCompile(`^[^@\s"'<>\\]{1,64}@[A-Za-z0-9.-]{1,190}\.[A-Za-z]{2,24}$`)
)

// WordPress installs WordPress sites.
type WordPress struct {
	Sites  *sites.Manager
	DB     *databases.Manager
	Store  *store.Store
	Runner execx.Runner
	// Fetch downloads a URL (limit bytes at most).
	Fetch   func(ctx context.Context, url string, limit int64) ([]byte, error)
	WebRoot string
	CLIPath string
	// PHPSocket overrides PHP-FPM socket detection (tests).
	PHPSocket string
}

// NewWordPress returns an installer with production settings.
func NewWordPress(st *store.Store, sm *sites.Manager, db *databases.Manager) *WordPress {
	return &WordPress{Sites: sm, DB: db, Store: st, Runner: execx.Exec{}, Fetch: httpFetch, WebRoot: "/var/www", CLIPath: wpCLIPath}
}

func httpFetch(ctx context.Context, url string, limit int64) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, "GET", url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "appanel")
	res, err := (&http.Client{Timeout: 5 * time.Minute}).Do(req)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	if res.StatusCode != 200 {
		return nil, fmt.Errorf("HTTP %d from %s", res.StatusCode, url)
	}
	b, err := io.ReadAll(io.LimitReader(res.Body, limit+1))
	if err != nil {
		return nil, err
	}
	if int64(len(b)) > limit {
		return nil, errors.New("download is larger than expected")
	}
	return b, nil
}

// WPInput is the form in the UI.
type WPInput struct {
	Domain     string `json:"domain"`
	Title      string `json:"title"`
	AdminUser  string `json:"admin_user"`
	AdminEmail string `json:"admin_email"`
	SSL        bool   `json:"ssl"`
}

// WPResult is shown once; the password is not stored.
type WPResult struct {
	URL           string `json:"url"`
	AdminURL      string `json:"admin_url"`
	AdminUser     string `json:"admin_user"`
	AdminPassword string `json:"admin_password,omitempty"`
	SiteID        int64  `json:"site_id"`
	SSL           bool   `json:"ssl"`
	// SetupInBrowser is true when the final WordPress setup step could not be
	// run automatically; the site is ready and its setup page will open.
	SetupInBrowser bool   `json:"setup_in_browser"`
	Log            string `json:"log"`
}

// Validate checks the form.
func (in *WPInput) Validate() error {
	in.Title = strings.TrimSpace(in.Title)
	in.AdminUser = strings.TrimSpace(in.AdminUser)
	in.AdminEmail = strings.TrimSpace(in.AdminEmail)
	if in.Title == "" || len(in.Title) > 100 {
		return errors.New("site title is required (100 characters max)")
	}
	for _, r := range in.Title {
		if r < 0x20 || r == 0x7f {
			return errors.New("site title has control characters")
		}
	}
	if !userRe.MatchString(in.AdminUser) {
		return errors.New("admin username must start with a letter and be 3-31 characters of letters, digits, . _ -")
	}
	if !emailRe.MatchString(in.AdminEmail) {
		return errors.New("admin email does not look valid")
	}
	return nil
}

const saltChars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_.,;:!@#%^&*()[]{}~"

func randString(alphabet string, n int) (string, error) {
	b := make([]byte, n)
	max := big.NewInt(int64(len(alphabet)))
	for i := range b {
		x, err := rand.Int(rand.Reader, max)
		if err != nil {
			return "", err
		}
		b[i] = alphabet[x.Int64()]
	}
	return string(b), nil
}

// RenderConfig builds wp-config.php. Every value is generated by us (no user
// text), so nothing needs escaping beyond what the alphabets already exclude.
func RenderConfig(dbName, dbUser, dbPass, prefix string, salts [8]string) string {
	keys := []string{"AUTH_KEY", "SECURE_AUTH_KEY", "LOGGED_IN_KEY", "NONCE_KEY", "AUTH_SALT", "SECURE_AUTH_SALT", "LOGGED_IN_SALT", "NONCE_SALT"}
	var b strings.Builder
	b.WriteString("<?php\n// Generated by Appanel.\n")
	fmt.Fprintf(&b, "define( 'DB_NAME', '%s' );\ndefine( 'DB_USER', '%s' );\ndefine( 'DB_PASSWORD', '%s' );\n", dbName, dbUser, dbPass)
	b.WriteString("define( 'DB_HOST', 'localhost' );\ndefine( 'DB_CHARSET', 'utf8mb4' );\ndefine( 'DB_COLLATE', '' );\n\n")
	for i, k := range keys {
		fmt.Fprintf(&b, "define( '%s', '%s' );\n", k, salts[i])
	}
	fmt.Fprintf(&b, "\n$table_prefix = '%s';\n\ndefine( 'WP_DEBUG', false );\ndefine( 'FS_METHOD', 'direct' );\n\n", prefix)
	b.WriteString("if ( ! defined( 'ABSPATH' ) ) {\n\tdefine( 'ABSPATH', __DIR__ . '/' );\n}\nrequire_once ABSPATH . 'wp-settings.php';\n")
	return b.String()
}

// ExtractWordPress unpacks the release tarball into root, dropping the
// leading "wordpress/" folder. Names that escape root and anything that is not
// a plain file or folder are rejected.
func ExtractWordPress(archive []byte, root string) error {
	gz, err := gzip.NewReader(strings.NewReader(string(archive)))
	if err != nil {
		return err
	}
	tr := tar.NewReader(gz)
	var total int64
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return err
		}
		name := path.Clean(strings.TrimPrefix(h.Name, "./"))
		if name == "." || name == "wordpress" {
			continue
		}
		if !strings.HasPrefix(name, "wordpress/") || strings.Contains(name, "..") || path.IsAbs(name) {
			return fmt.Errorf("unexpected path in archive: %q", h.Name)
		}
		rel := strings.TrimPrefix(name, "wordpress/")
		dst := filepath.Join(root, filepath.FromSlash(rel))
		if dst != root && !strings.HasPrefix(dst, root+string(filepath.Separator)) {
			return fmt.Errorf("unexpected path in archive: %q", h.Name)
		}
		switch h.Typeflag {
		case tar.TypeDir:
			if err := os.MkdirAll(dst, 0o755); err != nil {
				return err
			}
		case tar.TypeReg:
			total += h.Size
			if total > maxTarBytes {
				return errors.New("archive is larger than expected")
			}
			if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
				return err
			}
			f, err := os.OpenFile(dst, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o644)
			if err != nil {
				return err
			}
			if _, err := io.Copy(f, io.LimitReader(tr, h.Size)); err != nil {
				f.Close()
				return err
			}
			if err := f.Close(); err != nil {
				return err
			}
		default:
			return fmt.Errorf("unsupported entry in archive: %q", h.Name)
		}
	}
}

func hexField(b []byte, n int) (string, bool) {
	f := strings.Fields(string(b))
	if len(f) == 0 || len(f[0]) != n {
		return "", false
	}
	if _, err := hex.DecodeString(f[0]); err != nil {
		return "", false
	}
	return strings.ToLower(f[0]), true
}

// Install does everything. It returns the log even on failure.
func (w *WordPress) Install(ctx context.Context, in WPInput) (res WPResult, err error) {
	var log strings.Builder
	step := func(format string, a ...any) { fmt.Fprintf(&log, "• "+format+"\n", a...) }
	defer func() { res.Log = log.String() }()
	if err = in.Validate(); err != nil {
		return
	}
	domain, derr := sites.NormalizeDomain(in.Domain)
	if derr != nil {
		err = derr
		return
	}
	if _, derr := w.Sites.Store.SiteByDomain(domain); derr == nil {
		err = errors.New("a website with that domain already exists; WordPress is installed on a new, empty site")
		return
	}
	run := func(name string, args ...string) error {
		out, e := w.Runner.Run(ctx, name, args...)
		if e != nil {
			fmt.Fprintf(&log, "$ %s %s\n%s\n", name, strings.Join(args, " "), execx.Tail(out, 1500))
		}
		return e
	}

	// 1. Web stack: Nginx, Certbot, PHP and its extensions, MariaDB.
	if st := w.Sites.Status(ctx); !st.NginxInstalled || !st.CertbotInstalled {
		step("installing Nginx and Certbot")
		if out, e := w.Sites.Setup(ctx, true); e != nil {
			fmt.Fprintln(&log, out)
			err = errors.New("could not install Nginx")
			return
		}
	}
	step("making sure PHP and its extensions are installed")
	if e := run("apt-get", append([]string{"install", "-y", "-qq"}, phpPackages...)...); e != nil {
		err = errors.New("could not install PHP")
		return
	}
	if st := w.DB.Status(ctx, databases.MySQL); !st.Installed || !st.Running {
		step("installing MariaDB")
		if out, e := w.DB.Install(ctx, databases.MySQL); e != nil {
			fmt.Fprintln(&log, out)
			err = errors.New("could not install MariaDB")
			return
		}
	}

	// 2. Everything below is undone if a later step fails.
	var site store.Site
	var dbCreated *databases.Created
	siteRoot := filepath.Join(w.WebRoot, domain)
	defer func() {
		if err == nil {
			return
		}
		step("install failed; cleaning up")
		if dbCreated != nil {
			_ = w.DB.Drop(context.Background(), databases.MySQL, dbCreated.Name)
		}
		if site.ID != 0 {
			_ = w.Sites.Delete(context.Background(), site.ID)
			_ = os.RemoveAll(siteRoot)
		}
	}()

	step("creating the website %s", domain)
	site, err = w.Sites.Create(ctx, sites.CreateInput{Domain: domain, Type: store.SitePHP, PHPSocket: w.PHPSocket})
	if err != nil {
		return
	}
	// Remove the placeholder page; anything else in the folder means it is not new.
	ents, _ := os.ReadDir(site.Root)
	for _, e := range ents {
		if e.Name() == "index.html" {
			if b, _ := os.ReadFile(filepath.Join(site.Root, "index.html")); strings.Contains(string(b), "served by Appanel") {
				_ = os.Remove(filepath.Join(site.Root, "index.html"))
				continue
			}
		}
		err = errors.New("the site folder is not empty; refusing to overwrite it")
		return
	}

	step("creating the database")
	prefixName := regexp.MustCompile(`[^a-z0-9]`).ReplaceAllString(strings.Split(domain, ".")[0], "")
	if len(prefixName) > 18 {
		prefixName = prefixName[:18]
	}
	suffix, _ := randString("0123456789abcdef", 4)
	dbName := "wp_" + prefixName + "_" + suffix
	c, cerr := w.DB.Create(ctx, databases.MySQL, dbName)
	if cerr != nil {
		err = cerr
		return
	}
	dbCreated = &c

	step("downloading WordPress")
	archive, ferr := w.Fetch(ctx, wpURL, maxTarBytes)
	if ferr != nil {
		err = fmt.Errorf("could not download WordPress: %w", ferr)
		return
	}
	sumFile, ferr := w.Fetch(ctx, wpURL+".sha1", 4096)
	want, ok := hexField(sumFile, 40)
	if ferr != nil || !ok {
		err = errors.New("could not get WordPress's checksum; refusing to install an unverified download")
		return
	}
	if got := sha1.Sum(archive); hex.EncodeToString(got[:]) != want {
		err = errors.New("WordPress download failed its checksum; refusing to install it")
		return
	}
	step("unpacking")
	if err = ExtractWordPress(archive, site.Root); err != nil {
		return
	}

	var salts [8]string
	for i := range salts {
		if salts[i], err = randString(saltChars, 64); err != nil {
			return
		}
	}
	px, _ := randString("abcdefghijklmnopqrstuvwxyz0123456789", 4)
	cfg := RenderConfig(c.Name, c.User, c.Password, "wp"+px+"_", salts)
	if err = os.WriteFile(filepath.Join(site.Root, "wp-config.php"), []byte(cfg), 0o640); err != nil {
		return
	}
	if e := run("chown", "-R", "www-data:www-data", site.Root); e != nil {
		err = errors.New("could not set file ownership")
		return
	}

	// 3. HTTPS first (when asked), so WordPress is installed with its final address.
	scheme := "http"
	if in.SSL {
		step("requesting a Let's Encrypt certificate")
		if _, out, e := w.Sites.IssueSSL(ctx, site.ID); e != nil {
			fmt.Fprintf(&log, "! HTTPS could not be set up (%v). Continuing with HTTP; use \"Get SSL\" later.\n%s\n", e, out)
		} else {
			scheme, res.SSL = "https", true
		}
	}
	base := scheme + "://" + domain

	// 4. Final setup with WP-CLI, or leave it to the browser.
	adminPass, _ := randString("abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789", 20)
	if w.ensureCLI(ctx, &log) {
		step("running the WordPress setup")
		out, e := w.Runner.Run(ctx, "runuser", "-u", "www-data", "--", "php", w.CLIPath, "core", "install",
			"--path="+site.Root, "--url="+base, "--title="+in.Title, "--admin_user="+in.AdminUser,
			"--admin_password="+adminPass, "--admin_email="+in.AdminEmail, "--skip-email")
		if e != nil {
			fmt.Fprintf(&log, "! WP-CLI setup failed: %s\n", strings.ReplaceAll(execx.Tail(out, 600), adminPass, "***"))
			res.SetupInBrowser = true
		} else {
			res.AdminUser, res.AdminPassword = in.AdminUser, adminPass
		}
	} else {
		res.SetupInBrowser = true
	}
	if res.SetupInBrowser {
		step("the site is ready; finish the 5-minute setup in your browser")
	}

	site.App = "wordpress"
	if e := w.Store.UpdateSite(site); e != nil {
		step("could not label the site as WordPress: %v", e)
	}
	res.URL, res.AdminURL, res.SiteID = base+"/", base+"/wp-admin/", site.ID
	if res.SetupInBrowser {
		res.AdminURL = base + "/wp-admin/install.php"
	}
	return res, nil
}

// ensureCLI makes sure WP-CLI is present, downloading and verifying it once.
func (w *WordPress) ensureCLI(ctx context.Context, log *strings.Builder) bool {
	if _, err := os.Stat(w.CLIPath); err == nil {
		return true
	}
	phar, err := w.Fetch(ctx, wpCLIURL, 20<<20)
	sums, err2 := w.Fetch(ctx, wpCLIURL+".sha512", 4096)
	want, ok := hexField(sums, 128)
	if err != nil || err2 != nil || !ok {
		fmt.Fprintln(log, "! could not download WP-CLI; the setup will be finished in the browser")
		return false
	}
	if got := sha512.Sum512(phar); hex.EncodeToString(got[:]) != want {
		fmt.Fprintln(log, "! WP-CLI failed its checksum; not using it")
		return false
	}
	if err := os.WriteFile(w.CLIPath, phar, 0o755); err != nil {
		fmt.Fprintf(log, "! could not install WP-CLI: %v\n", err)
		return false
	}
	return true
}
